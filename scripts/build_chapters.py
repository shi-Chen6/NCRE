RE_CH = {k: [(re.compile(p), w) for p, w in v] for k, v in RULES.items()}


def score_of(text, ch):
    s = 0
    for pat, w in RE_CH[ch]:
        if pat.search(text):
            s += w
    return s


def classify(stem, options, analysis):
    """题干权重 4（考点就在题干里），选项权重 1、解析权重 1（只作辅助）。
    选项里常出现别的章的术语（如「完整的软件应包含」的选项写了数据库管理系统），
    权重放大就会串章，所以只给 1 分。"""
    opt = " ".join(options.values())
    best, best_score = 0, 0
    for ch in RULES:
        s = score_of(stem, ch) * 4 + score_of(opt, ch) + score_of(analysis, ch)
        if s > best_score:
            best, best_score = ch, s
    return best


def main():
    chapters = [{"id": cid, "name": name, "desc": desc} for cid, name, desc in CHAPTERS]
    valid = {c["id"] for c in chapters}

    assign = {}          # "套-题" -> 章 id
    rows = []            # 复核清单
    miss = []
    for i in range(1, SET_COUNT + 1):
        with open(os.path.join(DATA, "set_%02d.json" % i), encoding="utf-8") as f:
            d = json.load(f)
        with open(os.path.join(ANS, "set_%02d.json" % i), encoding="utf-8") as f:
            a = json.load(f)
        amap = {x["no"]: x for x in a["items"]}
        for q in d["questions"]:
            no = q["no"]
            key = "%d-%d" % (i, no)
            ai = amap.get(no, {})
            ch = OVERRIDES.get(key) or classify(q["stem"], q["options"], ai.get("analysis", ""))
            if ch not in valid:
                ch = 0
            assign[key] = ch
            rows.append((i, no, ch, q["stem"].strip()))
            if ch == 0:
                miss.append((i, no, q["stem"].strip()))

    # ---- 一致性断言
    total = sum(len(json.load(open(os.path.join(DATA, "set_%02d.json" % i), encoding="utf-8"))["questions"])
                for i in range(1, SET_COUNT + 1))
    assert len(assign) == total, "题目条数与源数据不一致：%d vs %d" % (len(assign), total)

    payload = {
        "version": 1,
        "chapters": chapters,
        "assign": assign,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=1)

    # ---- 复核清单
    cnt = {}
    for k, v in assign.items():
        cnt[v] = cnt.get(v, 0) + 1
    lines = ["# 知识点章节归属复核清单", "",
             "共 %d 题 · %d 章。章号 0 表示未归类。" % (len(assign), len(chapters)), "",
             "| 章 | 章名 | 题量 |", "|---|---|---|"]
    for c in chapters:
        lines.append("| %02d | %s | %d |" % (c["id"], c["name"], cnt.get(c["id"], 0)))
    lines.append("| — | 未归类 | %d |" % cnt.get(0, 0))
    lines.append("")

    by_ch = {}
    for i, no, ch, stem in rows:
        by_ch.setdefault(ch, []).append((i, no, stem))
    for c in sorted(by_ch):
        name = next((x["name"] for x in chapters if x["id"] == c), "未归类")
        lines.append("## %02d %s（%d 题）" % (c, name, len(by_ch[c])))
        lines.append("")
        for i, no, stem in sorted(by_ch[c]):
            lines.append("- `%d-%d` %s" % (i, no, stem[:60]))
        lines.append("")

    with open(REVIEW, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print("章节归属 ->", OUT)
    print("复核清单 ->", REVIEW)
    for c in chapters:
        print("  %02d %-16s %3d 题" % (c["id"], c["name"], cnt.get(c["id"], 0)))
    print("  未归类 %d 题" % cnt.get(0, 0))
    print("合计 %d 题" % sum(cnt.values()))


if __name__ == "__main__":
    main()
